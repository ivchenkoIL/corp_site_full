/* штатный файл сохранения игры, поставленный в нужную точку и час */
export function saveFor(sc) {
  return {
    v: 1, ts: Date.now(),
    p: { x: sc.p.x, z: sc.p.z, yaw: sc.p.yaw, health: 100, stamina: 100, drunk: 0,
         money: 1500, rep: 30, tools: ['screw', 'tester', 'ties', 'lamp'], tool: 0 },
    bike: { x: sc.bike.x, z: sc.bike.z, cond: 100 },
    clock: sc.hour * 3600, day: 1, heat: 0,
    missionIndex: 0, missionsDone: [], free: false, freeCount: 0,
    upgrades: {}, stats: { earned: 0, crashes: 0, fixed: 0, sober: 0, bestQ: 0, fines: 0, dist: 0 },
    flags: { tutorialDone: true },
    poles: new Array(24).fill(false), station: 0
  };
}

/* Настройки игры для замера. quality — профиль (low | medium | high);
   dynamic — авто-масштаб рендера. Для сравнимых цифр он выключен: иначе
   игра сама держит кадр в бюджете, и FPS упирается в частоту монитора, а
   меняется разрешение. lowFx оставлен ради сборок до этапа 02. */
export function optsFor(quality, dynamic) {
  return { camFollow: true, quality: quality || 'medium', dynamic: !!dynamic, lowFx: quality === 'low',
           station: 0, sfx: 0.7, mus: 0.5, muted: false };
}
