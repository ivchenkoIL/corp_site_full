/* =====================================================================
   yard.js — двор конторы «Монтаж-Сервис» в новой версии: деревья и
   лавка, которых не было у старой игры. Они добавляются в PROPS старой
   логики до сборки препятствий, поэтому Олег обходит их так же, как всё
   остальное, — а не проходит сквозь ствол.

   isYardFree — где можно сеять траву и сорняки: не на дорогах, не на
   тротуарах и отмостках (там их не бывает), не на тропинках двора.
   ===================================================================== */
import { surfY } from '../legacy/world/district.js';

export const YARD_PROPS = [
  { kind: 'tree', x: 1.8, z: 51.2, sp: 'birch' },
  { kind: 'tree', x: 16.2, z: 35.9, sp: 'birch' },
  { kind: 'tree', x: 1.9, z: 36.2, sp: 'poplar' },
  { kind: 'tree', x: 15.6, z: 58.7, sp: 'maple' },
  { kind: 'bench', x: 13.4, z: 48.95, a: 0 }
];

/* тропинки: к двери конторы, к гаражам, место сбора бригады */
const PATHS = [
  [7.0, 48.0, 17.2, 56.4],   /* пятачок перед дверью, где стоит бригада */
  [11.5, 33.0, 17.2, 38.8],  /* проход вдоль восточного торца */
  [2.4, 33.0, 12.2, 38.6]    /* площадка у северных гаражей */
];
export function isYardFree(x, z) {
  if (Math.abs(surfY(x, z) - 0.013) > 0.001) return false;
  for (const [x0, z0, x1, z1] of PATHS) if (x > x0 && x < x1 && z > z0 && z < z1) return false;
  for (const p of YARD_PROPS) if (Math.hypot(p.x - x, p.z - z) < 0.9) return false;
  return true;
}
