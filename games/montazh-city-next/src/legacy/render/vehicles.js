export function drawVehicle(kind, x, y, z, yaw, wheelPhase, tint, o) {
  const gl = GL.gl, P = R3.main;
  const spec = CAR_SPEC[kind];
  const pit = o ? o.pitch || 0 : 0, rol = o ? o.roll || 0 : 0, st = o ? o.steer || 0 : 0;
  /* кузов клюёт и кренится, колёсам нужна своя ровная база — иначе уедут в асфальт */
  m4compose(SCRATCH[6], x, y, z, 0, yaw, 0, 1);
  m4compose(BONES[0], x, y, z, pit, yaw, rol, 1);
  for (let i = 0; i < 4; i++) {
    const [ox, oz] = spec.wheels[i];
    m4mul(BONES[1 + i], SCRATCH[6], m4compose(SCRATCH[7], ox, spec.wr - y, oz, 0,
      Math.PI / 2 + (i < 2 ? st : 0), -wheelPhase, 1));
  }
  for (let i = 0; i < 5; i++) BONEBUF.set(BONES[i], i * 16);
  gl.uniformMatrix4fv(P.u.uBones, false, BONEBUF);
  drawMesh(VEH[kind], TX.paint, BONES[0], { skin: true, tint });
}
export function drawBike(x, y, z, yaw, wheelPhase, lean, steer, crank) {
  const gl = GL.gl, P = R3.main;
  const st = steer || 0;
  m4compose(BONES[0], x, y, z, 0, yaw, lean || 0, 1);
  /* вилка с рулём вращается вокруг рулевой колонки, переднее колесо — её ребёнок */
  m4mul(BONES[3], BONES[0], m4compose(SCRATCH[7], 0, 0.92, 0.30, 0, st, 0, 1));
  m4mul(BONES[1], BONES[3], m4compose(SCRATCH[7], 0, -0.58, 0.22, 0, Math.PI / 2, -wheelPhase, 1));
  m4mul(BONES[2], BONES[0], m4compose(SCRATCH[7], 0, 0.34, -0.52, 0, Math.PI / 2, -wheelPhase, 1));
  /* каретка: шатуны крутятся в такт с ногами всадника */
  m4mul(BONES[4], BONES[0], m4compose(SCRATCH[7], 0, 0.30, -0.02, crank || 0, 0, 0, 1));
  for (let i = 0; i < 5; i++) BONEBUF.set(BONES[i], i * 16);
  gl.uniformMatrix4fv(P.u.uBones, false, BONEBUF);
  drawMesh(VEH.bike, TX.paint, BONES[0], { skin: true });
}
