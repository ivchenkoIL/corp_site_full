    m.cyl(0, 0.30, -0.02, 0.045, 0.08, 10, DARK, { gloss: 0.5 });                      /* каретка */
    /* рулевой узел — отдельная кость 3, координаты от пивота (0, 0.92, 0.30):
       вилка, вынос, руль, грипсы и фара поворачиваются вместе с колесом */
    for (const sx of [-0.055, 0.055])
      m.tube([[sx * 1.1, 0, 0], [sx * 1.1, -0.58, 0.22]], 0.014, 6, STEEL, { gloss: 0.75, part: 3 });
