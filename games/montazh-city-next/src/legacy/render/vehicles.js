export function buildCar(gl, spec) {
  const body = new Mesh();                 /* «длиной по X», развернём в конце */
  const PAINT = [1, 1, 1];                 /* красится оттенком при отрисовке */
  const DARK = [.18, .18, .21], CHROME = [.72, .74, .80], GLASS = [.16, .21, .30];
  const hw = spec.hw, gw = spec.gw;
  const sl = (w, tapXY) => [
    { z: -w, sx: tapXY[0], sy: tapXY[1] }, { z: -w * 0.9, sx: 1, sy: 1 },
    { z: w * 0.9, sx: 1, sy: 1 }, { z: w, sx: tapXY[0], sy: tapXY[1] }
  ];
  /* --- корпус --- */
  body.extrudeZ(spec.body, sl(hw, [0.975, 0.955]), PAINT,
    { origin: [0, 0.58], uv: 1.6, gloss: 0.62, part: 0, smooth: 46 });
  /* --- остекление: тёмное стекло, поверх него стойки и крыша --- */
  body.extrudeZ(spec.glass, sl(gw, [0.94, 0.94]), GLASS,
    { origin: [0, 1.05], uv: 1, gloss: 0.95, part: 0, smooth: 30 });
  /* крыша */
  body.bevelBox(spec.roof[0], spec.roof[1] - 0.055, 0, spec.roof[2], 0.06, gw * 2.03, PAINT,
    { bev: 0.022, r: 0.10, cs: 3, part: 0, gloss: 0.6, uv: 1.4 });
  /* стойки по краям остекления */
  {
    const g = spec.glass, n = g.length;
    for (const sz of [-1, 1]) {
      const z = sz * (gw + 0.014);
      for (let i = 1; i < n; i++) {
        const a = g[i], b = g[(i + 1) % n];
        if (a[1] <= g[0][1] + 0.02 && b[1] <= g[0][1] + 0.02) continue;
        /* тонкая наклонная стойка вдоль ребра остекления */
        body.tube([[a[0], a[1], z], [b[0], b[1], z]], 0.035, 6, PAINT, { part: 0, gloss: 0.6 });
      }
      /* центральная стойка */
      if (spec.doors[1] !== null) {
        const yTop = spec.roof[1] - 0.05;
        body.tube([[spec.doors[1], spec.glass[0][1], z], [spec.doors[1] - 0.05, yTop, z]], 0.04, 6, PAINT, { part: 0, gloss: 0.6 });
      }
    }
  }
  /* --- бамперы --- */
  for (const [x, w] of [[spec.body[6][0] - 0.04, 0.26], [spec.body[16][0] + 0.04, 0.24]]) {
    body.bevelBox(x, 0.30, 0, w, 0.30, hw * 2.02, DARK,
      { bev: 0.05, r: 0.08, cs: 2, part: 0, gloss: 0.3, taper: [0.9, 1] });
  }
  /* --- решётка и фары --- */
  const fx = spec.body[7][0];
  body.bevelBox(fx - 0.03, 0.60, 0, 0.10, 0.20, hw * 1.15, DARK,
    { bev: 0.02, r: 0.05, cs: 2, part: 0, gloss: 0.4 });
  for (let i = 0; i < 3; i++)
    body.box(fx + 0.01, 0.63 + i * 0.055, 0, 0.05, 0.022, hw * 1.12, CHROME, { part: 0, gloss: 0.85 });
  for (const sz of [-1, 1]) {
    body.bevelBox(fx - 0.06, 0.62, sz * hw * 0.66, 0.14, 0.17, 0.34, [1, .96, .86],
      { bev: 0.025, r: 0.05, cs: 2, part: 0, gloss: 0.9, emis: 0.35 });
    body.bevelBox(spec.body[16][0] + 0.05, 0.60, sz * hw * 0.66, 0.10, 0.16, 0.30, [1, .26, .2],
      { bev: 0.02, r: 0.04, cs: 2, part: 0, gloss: 0.8, emis: 0.5 });
    /* повторители в бампере */
    body.box(fx - 0.02, 0.40, sz * hw * 0.78, 0.05, 0.07, 0.20, [1, .62, .18], { part: 0, gloss: 0.7, emis: 0.25 });
  }
  /* номерные знаки */
  body.box(fx - 0.05, 0.42, 0, 0.03, 0.11, 0.42, [.88, .89, .86], { part: 0, gloss: 0.4 });
  body.box(spec.body[16][0] + 0.06, 0.44, 0, 0.03, 0.11, 0.42, [.88, .89, .86], { part: 0, gloss: 0.4 });
  /* --- арки колёс --- */
  for (const [ax, ar] of spec.arches) {
    for (const sz of [-1, 1]) {
      const pts = [];
      for (let i = 0; i <= 8; i++) {
        const a = Math.PI * (0.06 + 0.88 * i / 8);
        pts.push([ax + Math.cos(a) * ar, spec.wr + Math.sin(a) * ar, sz * (hw - 0.03)]);
      }
      body.tube(pts, 0.045, 6, PAINT, { part: 0, gloss: 0.5 });
    }
  }
  /* --- двери: расшивка, ручки, зеркала, пороги --- */
  for (const sz of [-1, 1]) {
    const z = sz * (hw + 0.005);
    for (const dx of spec.doors) {
      if (dx === null) continue;
      body.box(dx, 0.55, z, 0.018, 0.62, 0.02, [.12, .12, .14], { part: 0, gloss: 0.2 });
      body.bevelBox(dx - 0.30, 0.78, z - sz * 0.005, 0.20, 0.045, 0.05, CHROME,
        { bev: 0.008, r: 0.015, cs: 2, part: 0, gloss: 0.85 });
    }
    body.box(0.2, 0.24, z - sz * 0.03, 2.2, 0.09, 0.06, DARK, { part: 0, gloss: 0.25 });   /* порог */
    /* зеркало на стойке */
    const mz = spec.glass[1][0];
    body.box(mz - 0.06, spec.glass[0][1] + 0.06, z + sz * 0.06, 0.07, 0.035, 0.10, DARK, { part: 0, gloss: 0.4 });
    body.bevelBox(mz - 0.06, spec.glass[0][1] + 0.02, z + sz * 0.14, 0.10, 0.13, 0.06, PAINT,
      { bev: 0.02, r: 0.02, cs: 2, part: 0, gloss: 0.6 });
  }
  /* --- крышка капота и багажника: расшивка --- */
  body.box(spec.hood[0], spec.hood[1], 0, 1.1, 0.012, hw * 1.7, [.1, .1, .12], { part: 0, gloss: 0.3 });
  if (spec.trunk) body.box(spec.trunk[0], spec.trunk[1], 0, 0.5, 0.012, hw * 1.7, [.1, .1, .12], { part: 0, gloss: 0.3 });
  /* кузов пикапа: борта */
  if (spec.bed) {
    const [bx, by, bl] = spec.bed;
    for (const sz of [-1, 1])
      body.bevelBox(bx, by, sz * (hw - 0.09), bl, 0.34, 0.10, PAINT, { bev: 0.02, r: 0.03, cs: 2, part: 0, gloss: 0.55 });
    body.bevelBox(bx - bl / 2 - 0.05, by, 0, 0.10, 0.34, hw * 1.82, PAINT, { bev: 0.02, r: 0.03, cs: 2, part: 0, gloss: 0.55 });
    body.plate(bx - bl / 2, -(hw - 0.14), bx + bl / 2, hw - 0.14, by + 0.005, [.42, .42, .46], 0.5, 0, false, 0.2);
  }
  /* багажник на крыше у фургона */
  if (spec.tall) {
    for (const sz of [-1, 1])
      body.tube([[spec.roof[0] - 1.3, spec.roof[1] + 0.06, sz * gw * 0.72], [spec.roof[0] + 1.3, spec.roof[1] + 0.06, sz * gw * 0.72]],
        0.028, 6, CHROME, { part: 0, gloss: 0.8 });
    body.box(spec.roof[0], spec.roof[1] + 0.02, 0, 0.10, 0.06, gw * 1.5, CHROME, { part: 0, gloss: 0.8 });
  }
  /* выхлоп */
  body.tube([[spec.body[16][0] + 0.10, 0.26, -hw * 0.55], [spec.body[16][0] - 0.06, 0.26, -hw * 0.55]], 0.035, 6, [.4, .4, .44], { part: 0, gloss: 0.7 });

  body.aoByHeight(QCFG.light.bodyAO.y0, QCFG.light.bodyAO.y1, QCFG.light.bodyAO.k);
  body.rotY(-Math.PI / 2);                 /* нос — в сторону +Z */

  const m = new Mesh();
  m.merge(body, 0, 0, 0);
  for (let i = 0; i < 4; i++)
    m.wheelDetailed(spec.wr, 0.22, 14, [.11, .11, .13], [.70, .72, .78], 1 + i, { spokes: 5, rimR: spec.wr * 0.60, gloss: 0.45 });
  return m.upload(gl);
}

