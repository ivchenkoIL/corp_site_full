export function __set_Q(v) { Q = v; return v; }

/* ---------------------------------------------------------------------
   Исполняемая часть раздела. В монолите эти операторы шли вперемешку с
   функциями выше; здесь они в __init(), который main.js зовёт в исходном
   порядке разделов, — так порядок исполнения остаётся прежним.
   --------------------------------------------------------------------- */
export function __init() {

  /* Крючок замера: ?mc3d-cfg=<json> накладывается поверх QCFG до применения
     профиля. Нужен, чтобы мерить развилки, не пересобирая файл — например,
     выбор между разрешением глубины блитом и отдельным проходом:
       node tools/scale-probe.mjs --cfg='{"post":{"depthMS":"prepass"}}'
     В обычном запуске из file:// строки запроса нет и ветка не исполняется. */
  try {
    const _m = /[?&]mc3d-cfg=([^&]*)/.exec(location.search);
    if (_m) (function merge(dst, src) {
      for (const k in src) {
        if (src[k] && typeof src[k] === 'object' && !Array.isArray(src[k]) && dst[k] && typeof dst[k] === 'object') merge(dst[k], src[k]);
        else dst[k] = src[k];
      }
    })(QCFG, JSON.parse(decodeURIComponent(_m[1])));
  } catch (e) { console.warn('mc3d-cfg: ' + e.message); }
}
