/* Ваня объясняет один раз и в свободном режиме — но не каждую заявку */
export function freeVanya(n) {
  if (n % 3) return null;
  return [{ who: 'vanya', text: pick([
    'Олег, короткая вводная: делаешь как умеешь, но лучше как надо. Объясняю один раз.',
    'По объекту: там до тебя был Костя. Больше ничего не скажу, сам увидишь.',
    'Задача простая. Настолько простая, что Костя её уже испортил дважды.']) }];
}
/* след Кости встречается и в свободных заявках — через одну */
export function freeKostya(n) {
  if (n % 2) return null;
  return { trace: pick([
      'Кабель заведён поверх лотка и прихвачен изолентой. Изолента синяя — фирменный костин цвет.',
      'Клеммы затянуты через одну, зато быстро. В журнале отметка «выполнено».',
      'Стяжки затянуты насмерть, а кронштейн — от руки. Логика есть, но не та.']),
    fix: 'Переделать нормально', keep: 'Оставить как есть', fixQ: 6, keepQ: -8 };
}
export function makeFreeMission(n) {
  const camera = n % 2 === 1, who = pick(FREE_CLIENTS), urgent = n % 4 === 0;
  const pay = Math.round(clamp(1400 + n * 190, 1400, 4200));
  if (camera) {
    const pole = pick(POLES.filter(p => p.mount));
    const zone = pick(FREE_ZONES);
    return { id: 'free' + n, title: 'ЗАЯВКА №' + n + ': КАМЕРА', kind: 'camera', pay, zone,
      site: { x: pole.x, z: pole.z + 2.2, label: 'Опора ' + pole.mount },
      client: { who, x: pole.x - 3.5, z: pole.z + 4, name: CHARS[who].name },
      tools: ['screw', 'ladder', 'cable', 'ties'], time: urgent ? 300 : 0,
      vanya: freeVanya(n), kostya: freeKostya(n),
      brief: [
        { who: 'tamara', text: 'Олег, ещё одна. Опора ' + pole.mount + ', нужна камера на «' + zone + '». ' + (urgent ? 'И это срочно, у заказчика проверка.' : 'Без спешки, но и без ночёвки.') },
        { who: 'oleg', text: pick(['Понял. Опора, кронштейн, судьба.', 'Еду. Надеюсь, лестница ещё цела.', 'Ещё одна камера — ещё один взгляд на этот двор.']) }
      ],
      done: 'Картинка есть, «' + zone + '» видно. Заказчик кивнул — это максимум эмоций.' };
  }
  const d = pick(FREE_DOORS);
  return { id: 'free' + n, title: 'ЗАЯВКА №' + n + ': ДВЕРЬ', kind: 'door', pay,
    site: { x: d.x, z: d.z, label: d.label },
    client: { who, x: d.cx, z: d.cz, name: CHARS[who].name },
    tools: ['screw', 'tester', 'cable', 'drill'], time: urgent ? 280 : 0,
    vanya: freeVanya(n), kostya: freeKostya(n),
    brief: [
      { who: 'tamara', text: 'Заявка: ' + d.label + '. ' + pick(['Дверь живёт своей жизнью.', 'Замок открывается по настроению.', 'Считыватель молчит, как партизан.', 'Жильцы придумали свой способ входа. Он им нравится больше.']) + (urgent ? ' И да, это срочно.' : '') },
      { who: 'oleg', text: pick(['Значит, снова контроллер и совесть.', 'Еду. Дверь подождёт, люди — нет.', 'Хорошо. Только пусть на этот раз никто не помогает.']) }
    ],
    done: 'Дверь открывается, журнал пишет. Всё как надо.' };
}
